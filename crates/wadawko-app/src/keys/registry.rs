pub fn prefix_title(prefix: &str) -> Option<&'static str> {
    // a exibição do GPUI põe letras em maiúscula ("space D"); compara sem caixa
    PREFIX_TITLES.iter().find(|(p, _)| p.eq_ignore_ascii_case(prefix)).map(|(_, t)| *t)
}
